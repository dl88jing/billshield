import { chromium } from "playwright";
const url = process.argv[2] || "https://billshield-kappa.vercel.app";
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const errs = []; p.on("pageerror", (e) => errs.push(e.message));
await p.goto(url, { waitUntil: "networkidle" });
await p.screenshot({ path: "shots/01-landing.png" });
console.log("caps:", await p.locator('[data-testid=caps]').innerText());
await p.click('[data-testid=sample-1]');
await p.click('[data-testid=run]');
await p.waitForSelector('[data-testid=letter]', { timeout: 60000 });
for (const k of ["scan","device","gate","audit","letter"]) console.log(k, await p.getAttribute(`[data-testid=step-${k}]`, "data-state"));
console.log("stake:", await p.locator('[data-testid=stake]').innerText());
console.log("gate:", await p.locator('[data-testid=gate]').innerText());
const payload = await p.locator('[data-testid=receipt] pre').innerText();
console.log("payload has name placeholder:", /\[NAME_\d+\]/.test(payload));
await p.screenshot({ path: "shots/02-result.png", fullPage: true });
await p.goto(url + "/eval", { waitUntil: "networkidle" });
await p.screenshot({ path: "shots/03-eval.png", fullPage: false });
console.log("errors:", errs);
await b.close();
