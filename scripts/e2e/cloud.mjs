import { chromium } from "playwright";
const url = process.argv[2] || "https://billshield-kappa.vercel.app";
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome", headless: true });
const p = await b.newPage({ viewport: { width: 1440, height: 1000 } });
const net = [];
p.on("console", (m) => { if (/error|warn/i.test(m.type())) net.push("console." + m.type() + ": " + m.text().slice(0, 400)); });
p.on("response", async (r) => { const u = r.url(); if (/firebasevertexai|generativelanguage|firebaseappcheck|firebaseremoteconfig|firestore|recaptcha\/api2\/reload|exchangeRecaptcha/.test(u)) { let body = ""; if (r.status() >= 400) { try { body = (await r.text()).slice(0, 600); } catch {} } net.push(`${r.status()} ${r.request().method()} ${u.split("?")[0]} ${body}`); } });
await p.goto(url, { waitUntil: "networkidle" });
await p.waitForTimeout(9000);
console.log("caps:", (await p.locator('[data-testid=caps]').innerText()).replace(/\n/g, " | "));
await p.click('[data-testid=sample-1]'); await p.click('[data-testid=run]');
await p.waitForSelector('[data-testid=letter]', { timeout: 90000 });
await p.waitForTimeout(7000);
console.log("letter source:", await p.getAttribute('[data-testid=letter-source]', "data-source"), "|", await p.locator('[data-testid=letter-source]').innerText());
console.log("gate:", await p.locator('[data-testid=gate]').innerText());
console.log("appcheck receipt:", await p.locator('[data-testid=receipt-appcheck]').innerText());
if (await p.locator('[data-testid=ai-error]').count()) console.log("AI ERROR:", await p.locator('[data-testid=ai-error]').innerText());
console.log("firestore:", await p.locator('[data-testid=store]').innerText());
console.log("letter head:", (await p.locator('[data-testid=letter] pre').innerText()).slice(0, 500));
await p.screenshot({ path: "shots/cloud-result.png", fullPage: true });
console.log("--- network/console ---\n" + net.join("\n"));
await b.close();
